import json
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset
from torchvision import transforms
from PIL import Image

from elpv_dataset.utils import load_dataset


class ELPVDataset(Dataset):
    """
    Permanent PyTorch Dataset for the ELPV dataset.

    The dataset NEVER creates a new train/validation/test split.

    Instead, it loads the fixed split_manifest.json generated by
    splits.py. This guarantees that the same samples remain in
    train, validation, and test across different runs.

    Primary task:
        4-class ordinal defect severity classification.

    Ordinal classes:
        0 -> Healthy
        1 -> Mild
        2 -> Moderate
        3 -> Severe

    ELPV probability mapping:
        0.0      -> Healthy
        1/3      -> Mild
        2/3      -> Moderate
        1.0      -> Severe

    Binary functional/defective classification is NOT part of
    this default dataset representation. It can be created later
    as a separate derived experiment.
    """

    # --------------------------------------------------------
    # Ordinal severity definition
    # --------------------------------------------------------

    PROBA_TO_CLASS = {
        0.0: 0,
        round(1 / 3, 6): 1,
        round(2 / 3, 6): 2,
        1.0: 3
    }

    CLASS_NAMES = [
        "Healthy",
        "Mild",
        "Moderate",
        "Severe"
    ]

    # --------------------------------------------------------
    # Dataset initialization
    # --------------------------------------------------------

    def __init__(
        self,
        split,
        manifest_path=None,
        transform=None,
        normalize_stats=None
    ):
        """
        Parameters
        ----------
        split : str
            One of:
                "train"
                "val"
                "test"

        manifest_path : str or Path, optional
            Path to split_manifest.json.

            If omitted, the project-root manifest created by
            splits.py is used automatically.

        transform : torchvision transform, optional
            Optional image transformation applied before
            normalization.

        normalize_stats : tuple(float, float), optional
            (mean, std) used for normalization.

            For training:
                If omitted, mean/std are calculated from the
                training split only.

            For validation/test:
                Must be supplied using the training statistics.
        """

        # ----------------------------------------------------
        # Validate split name
        # ----------------------------------------------------

        if split not in ("train", "val", "test"):
            raise ValueError(
                "split must be one of: 'train', 'val', 'test'"
            )

        self.split = split

        # ----------------------------------------------------
        # Locate split_manifest.json
        # ----------------------------------------------------

        if manifest_path is None:
            # dataset.py:
            # models/backbone/modules/dataset.py
            #
            # parents[0] -> modules
            # parents[1] -> backbone
            # parents[2] -> models
            # parents[3] -> project root

            project_root = Path(__file__).resolve().parents[3]
            manifest_path = project_root / "split_manifest.json"

        else:
            manifest_path = Path(manifest_path)

        if not manifest_path.exists():
            raise FileNotFoundError(
                f"split_manifest.json not found at:\n{manifest_path}\n\n"
                "Run splits.py first."
            )

        # ----------------------------------------------------
        # Load locked split
        # ----------------------------------------------------

        with open(manifest_path, "r") as f:
            manifest = json.load(f)

        idx = np.array(
            manifest[f"{split}_idx"],
            dtype=np.int64
        )

        # ----------------------------------------------------
        # Load official ELPV data
        # ----------------------------------------------------

        images, proba, types = load_dataset()

        # ----------------------------------------------------
        # Select only samples belonging to this split
        # ----------------------------------------------------

        self.images = images[idx]

        # Keep mono/poly type information for later analysis.
        # IMPORTANT:
        # "types" is NOT a physical module identifier.
        self.types = np.asarray(types)[idx]

        selected_proba = np.asarray(proba)[idx]

        # ----------------------------------------------------
        # Convert probabilities to ordinal class labels
        # ----------------------------------------------------

        self.labels = np.array(
            [
                self.PROBA_TO_CLASS[round(float(p), 6)]
                for p in selected_proba
            ],
            dtype=np.int64
        )

        # ----------------------------------------------------
        # Calculate/reuse normalization statistics
        # ----------------------------------------------------

        if normalize_stats is None:

            if split != "train":
                raise ValueError(
                    "normalize_stats must be supplied for "
                    "validation and test datasets. "
                    "Use the statistics calculated from the "
                    "training split."
                )

            # Calculate statistics ONLY from training images.
            #
            # Scaling to [0, 1] happens before calculating
            # mean and standard deviation.

            pixels = (
                self.images.astype(np.float32) / 255.0
            )

            mean = float(pixels.mean())
            std = float(pixels.std())

        else:
            mean, std = normalize_stats

        self.computed_stats = (mean, std)

        # ----------------------------------------------------
        # Image transformations
        # ----------------------------------------------------

        if transform is None:

            self.transform = transforms.Compose([
                transforms.ToTensor(),
                transforms.Normalize(
                    mean=[mean],
                    std=[std]
                )
            ])

        else:
            self.transform = transform

    # --------------------------------------------------------
    # Number of samples
    # --------------------------------------------------------

    def __len__(self):
        return len(self.images)

    # --------------------------------------------------------
    # Retrieve one sample
    # --------------------------------------------------------

    def __getitem__(self, index):

        image = self.images[index]

        # ELPV images are 8-bit grayscale.
        image = image.astype(np.uint8)

        # Convert NumPy array to PIL grayscale image.
        image = Image.fromarray(
            image,
            mode="L"
        )

        # Apply transformation.
        image = self.transform(image)

        label = torch.tensor(
            self.labels[index],
            dtype=torch.long
        )

        return image, label